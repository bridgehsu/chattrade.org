/** Lucide-style stroke icons as CSS mask data-URIs, keyed by section title. */
function svg(paths) {
  const body = paths.map((d) =>
    d.startsWith('<') ? d : `<path d="${d}"/>`
  ).join('')
  const raw =
    `<svg xmlns="http://www.w3.org/2000/svg" fill="none" stroke="black" stroke-width="2" ` +
    `stroke-linecap="round" stroke-linejoin="round" viewBox="0 0 24 24">${body}</svg>`
  return `url("data:image/svg+xml,${encodeURIComponent(raw)}")`
}

