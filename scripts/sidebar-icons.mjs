export function buildSidebarIconCss(sectionTitles) {
  const lines = [
    '/* Auto-generated by `npm run gen` — edit scripts/sidebar-icons.mjs instead. */'
  ]
  sectionTitles.forEach((title, index) => {
    const ico = SECTION_ICONS[title]
    if (!ico) return
    lines.push(
      `.VPSidebar .group:nth-child(${index + 1})>.VPSidebarItem.level-0{--nav-ico:${ico}} /* ${title} */`
    )
  })
  return `${lines.join('\n')}\n`
}
